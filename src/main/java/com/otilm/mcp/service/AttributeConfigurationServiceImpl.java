package com.otilm.mcp.service;

import com.otilm.api.model.core.auth.Resource;
import com.otilm.mcp.client.ConfigurationApiClient;
import java.util.Set;
import org.springframework.stereotype.Service;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.ObjectNode;

import static com.otilm.mcp.service.ConfigurationSupport.describe;
import static com.otilm.mcp.service.ConfigurationSupport.object;
import static com.otilm.mcp.service.ConfigurationSupport.required;
import static com.otilm.mcp.service.ConfigurationSupport.run;
import static com.otilm.mcp.service.ConfigurationSupport.uuid;

@Service
public class AttributeConfigurationServiceImpl implements AttributeConfigurationService {
    private static final String ATTRIBUTE_UUID = "Attribute UUID";
    private static final String CONTENT = "content";
    private static final String CONTENT_TYPE = "contentType";
    private static final String DESCRIPTION = "description";
    private static final String EXTENSIBLE_LIST = "extensibleList";
    private static final String GROUP = "group";
    private static final String LABEL = "label";
    private static final String MULTI_SELECT = "multiSelect";
    private static final String PROTECTION_LEVEL = "protectionLevel";
    private static final String READ_ONLY = "readOnly";
    private static final String REFERENCE = "reference";
    private static final String REQUIRED = "required";
    private static final String RESOURCES = "resources";
    private static final String VISIBLE = "visible";

    private static final String CUSTOM_ATTRIBUTE_ENDPOINT = "/v1/attributes/custom/{uuid}";
    private static final String RESOURCE = "/v1/attributes/custom/resources/{resource}";
    private static final String VALUE = RESOURCE + "/objects/{objectUuid}/{attributeUuid}";
    private static final String[] EDITABLE = {
            LABEL,
            DESCRIPTION,
            VISIBLE,
            GROUP,
            REQUIRED,
            READ_ONLY,
            "list",
            MULTI_SELECT,
            EXTENSIBLE_LIST,
            PROTECTION_LEVEL,
            CONTENT,
            RESOURCES};
    private static final String[] FIELDS = {
            "uuid",
            "name",
            LABEL,
            DESCRIPTION,
            "enabled",
            CONTENT_TYPE,
            VISIBLE,
            GROUP,
            REQUIRED,
            READ_ONLY,
            "list",
            MULTI_SELECT,
            EXTENSIBLE_LIST,
            PROTECTION_LEVEL,
            RESOURCES};
    private static final Set<String> CONTENT_TYPES = Set
            .of("string", "text", "integer", "float", "boolean", "date", "time", "datetime", "secret", "file",
                    "credential", "codeblock", "object");
    private final ConfigurationApiClient api;

    public AttributeConfigurationServiceImpl(ConfigurationApiClient api) {
        this.api = api;
    }

    @Override
    public String getCustomAttribute(String uuid) {
        return run("getting custom attribute", () -> describe("Custom attribute",
                api.get(CUSTOM_ATTRIBUTE_ENDPOINT, uuid(uuid, ATTRIBUTE_UUID)), FIELDS));
    }

    @Override
    public String createCustomAttributeDefinition(String configuration) {
        return run("creating custom attribute definition", () -> {
            ObjectNode body = object(configuration, "Definition");
            AdministrationInput
                    .allow(body, "name", CONTENT_TYPE, LABEL, DESCRIPTION, VISIBLE, GROUP, REQUIRED, READ_ONLY, "list",
                            MULTI_SELECT, EXTENSIBLE_LIST, PROTECTION_LEVEL, CONTENT, RESOURCES);
            if (body.has("uuid") || body.has("enabled")) {
                throw new IllegalArgumentException("UUID and enabled are generated by ILM.");
            }
            AdministrationInput.text(body, "name", CONTENT_TYPE);
            body.put("name", required(body.path("name").asString(null), "Attribute name"));
            String type = body.path(CONTENT_TYPE).asString();
            if (!CONTENT_TYPES.contains(type)) {
                throw new IllegalArgumentException("Unknown custom attribute content type.");
            }
            finish(body, body, true);
            return describe("Custom attribute created", api.post("/v1/attributes/custom", body), FIELDS);
        });
    }

    @Override
    public String updateCustomAttribute(String uuid, String configuration) {
        return run("updating custom attribute", () -> {
            String id = uuid(uuid, ATTRIBUTE_UUID);
            ObjectNode patch = AdministrationInput.configuration(configuration, EDITABLE);
            JsonNode existing = api.get(CUSTOM_ATTRIBUTE_ENDPOINT, id);
            ObjectNode body = AdministrationInput.select(existing, EDITABLE);
            if (!patch.has(CONTENT) && existing.path(CONTENT).isArray() && !existing.path(CONTENT).isEmpty()
                    && (AttributeContentValues.protectedValue(existing)
                            || AttributeContentValues.masked(existing.path(CONTENT)))) {
                throw new IllegalArgumentException(
                        "Protected definition content requires fresh content before replacement.");
            }
            patch.properties().forEach(entry -> body.set(entry.getKey(), entry.getValue()));
            finish(body, existing, patch.has(CONTENT));
            return describe("Custom attribute updated", api.put(CUSTOM_ATTRIBUTE_ENDPOINT, body, id), FIELDS);
        });
    }

    @Override
    public String enableCustomAttribute(String uuid) {
        return enabled(uuid, true);
    }

    @Override
    public String disableCustomAttribute(String uuid) {
        return enabled(uuid, false);
    }

    @Override
    public String deleteCustomAttribute(String uuid) {
        return run("deleting custom attribute", () -> {
            api.delete(CUSTOM_ATTRIBUTE_ENDPOINT, uuid(uuid, ATTRIBUTE_UUID));
            return "Custom attribute deleted.";
        });
    }

    @Override
    public String getCustomAttributeResources() {
        return run("getting custom attribute resources", () -> {
            JsonNode entries = api.get("/v1/attributes/custom/resources");
            StringBuilder result = new StringBuilder("Available custom attribute resources:\n");
            for (JsonNode entry : entries) {
                result.append(resource(entry.asString())).append('\n');
            }
            return result.toString();
        });
    }

    @Override
    public String getResourceCustomAttributes(String resource) {
        return run("getting resource custom attributes",
                () -> ConfigurationAttributes.settings("Custom attributes", api.get(RESOURCE, resource(resource))));
    }

    @Override
    public String setCustomAttributeResources(String uuid, String resources, boolean replace) {
        return run("replacing custom attribute resources", () -> {
            AdministrationInput.replaceIntent(replace);
            JsonNode parsed;
            try {
                parsed = AdministrationInput.JSON.readTree(resources);
            } catch (RuntimeException invalid) {
                throw new IllegalArgumentException("Resources must be a JSON array of resource codes.");
            }
            ArrayNode checked = resources(parsed);
            api.patch(CUSTOM_ATTRIBUTE_ENDPOINT + "/resources", checked, uuid(uuid, ATTRIBUTE_UUID));
            return "Custom attribute resource list replaced.";
        });
    }

    @Override
    public String setCustomAttributeValue(String resource, String objectUuid, String attributeUuid, String value) {
        return run("setting custom attribute value", () -> {
            String target = resource(resource);
            String object = uuid(objectUuid, "Object UUID");
            String attribute = uuid(attributeUuid, ATTRIBUTE_UUID);
            JsonNode definition = null;
            for (JsonNode candidate : api.get(RESOURCE, target)) {
                if (attribute.equals(candidate.path("uuid").asString())) {
                    definition = candidate;
                }
            }
            if (definition == null) {
                throw new IllegalArgumentException(
                        "Custom attribute is not assigned to this resource or is unavailable.");
            }
            if (ConfigurationAttributes.property(definition, READ_ONLY)) {
                throw new IllegalArgumentException("Custom attribute is read only.");
            }
            ArrayNode content = customValueContent(definition, value);
            api.patch(VALUE, content, target, object, attribute);
            return "Custom attribute [" + attribute + "] value updated on object [" + object + "].";
        });
    }

    private static ArrayNode customValueContent(JsonNode definition, String value) {
        JsonNode parsed;
        try {
            parsed = AdministrationInput.JSON.readTree(value);
        } catch (RuntimeException invalid) {
            throw new IllegalArgumentException("Attribute value must be valid JSON.");
        }
        if (parsed == null || parsed.isNull()) {
            throw new IllegalArgumentException("Supply a value; use delete_custom_attribute_value to clear it.");
        }
        ArrayNode content = AttributeContentValues.encode(definition, parsed);
        if (content.isEmpty()) {
            throw new IllegalArgumentException("Supply a value; use delete_custom_attribute_value to clear it.");
        }
        return content;
    }

    @Override
    public String deleteCustomAttributeValue(String resource, String objectUuid, String attributeUuid) {
        return run("deleting custom attribute value", () -> {
            api.delete(VALUE, resource(resource), uuid(objectUuid, "Object UUID"), uuid(attributeUuid, ATTRIBUTE_UUID));
            return "Custom attribute value deleted.";
        });
    }

    private String enabled(String uuid, boolean enabled) {
        return run("changing custom attribute state", () -> {
            api.patch(CUSTOM_ATTRIBUTE_ENDPOINT + (enabled ? "/enable" : "/disable"), null, uuid(uuid, ATTRIBUTE_UUID));
            return "Custom attribute " + (enabled ? "enabled." : "disabled.");
        });
    }

    private static ArrayNode resources(JsonNode values) {
        ArrayNode checked = AdministrationInput.strings(values, "Resources", false);
        checked.forEach(value -> resource(value.asString()));
        return checked;
    }

    private static String resource(String value) {
        return Resource
                .getCustomAttributesResources()
                .stream()
                .filter(candidate -> candidate.getCode().equals(value))
                .findFirst()
                .map(Resource::getCode)
                .orElseThrow(() -> new IllegalArgumentException("Unsupported custom attribute resource code."));
    }

    private static void finish(ObjectNode body, JsonNode existing, boolean freshContent) {
        AdministrationInput.text(body, LABEL, DESCRIPTION, GROUP, PROTECTION_LEVEL);
        body.put(LABEL, required(body.path(LABEL).asString(null), "Attribute label"));
        for (String flag : new String[]{VISIBLE, REQUIRED, READ_ONLY, "list", MULTI_SELECT, EXTENSIBLE_LIST}) {
            AdministrationInput.bool(body, flag);
        }
        String protection = body.path(PROTECTION_LEVEL).asString("none");
        if (!Set.of("none", "encrypted").contains(protection)) {
            throw new IllegalArgumentException("Protection level must be none or encrypted.");
        }
        if (body.has(RESOURCES)) {
            body.set(RESOURCES, resources(body.path(RESOURCES)));
        }
        if (!body.has(CONTENT)) {
            return;
        }
        JsonNode supplied = body.path(CONTENT);
        if (!supplied.isArray()) {
            throw new IllegalArgumentException("Definition content must be an array of data/reference objects.");
        }
        if (!freshContent) {
            return;
        }
        ObjectNode schema = AdministrationInput.JSON
                .createObjectNode()
                .put("name", existing.path("name").asString("Custom attribute"))
                .put(CONTENT_TYPE, existing.path(CONTENT_TYPE).asString())
                .put("version", 2);
        ArrayNode encoded = AdministrationInput.JSON.createArrayNode();
        for (JsonNode entry : supplied) {
            encoded.add(definitionContent(schema, entry));
        }
        body.set(CONTENT, encoded);
    }

    private static ObjectNode definitionContent(JsonNode schema, JsonNode entry) {
        if (!entry.isObject()) {
            throw new IllegalArgumentException("Definition content must contain data/reference objects.");
        }
        AdministrationInput.allow(entry, REFERENCE, "data", CONTENT_TYPE);
        AdministrationInput.text(entry, REFERENCE, CONTENT_TYPE);
        if (entry.hasNonNull(CONTENT_TYPE)
                && !entry.path(CONTENT_TYPE).asString().equals(schema.path(CONTENT_TYPE).asString())) {
            throw new IllegalArgumentException("Definition content type must match the attribute.");
        }
        if (entry.hasNonNull("data")) {
            ObjectNode content = (ObjectNode) AttributeContentValues.encode(schema, entry.path("data")).get(0);
            if (entry.hasNonNull(REFERENCE)) {
                content.set(REFERENCE, entry.path(REFERENCE));
            }
            return content;
        }
        if (entry.hasNonNull(REFERENCE)) {
            return AdministrationInput.select(entry, REFERENCE);
        }
        throw new IllegalArgumentException("Definition content needs data or a reference.");
    }
}
